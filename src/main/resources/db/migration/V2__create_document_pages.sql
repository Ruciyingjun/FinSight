-- 文档页面迁移：保存解析后的逐页文本及其在原始文档中的页码。
CREATE TABLE document_pages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id VARCHAR(36) NOT NULL,
    page_number INTEGER NOT NULL,
    content TEXT NOT NULL,
    character_count INTEGER NOT NULL,
    CONSTRAINT fk_document_pages_document
        FOREIGN KEY (document_id) REFERENCES documents (id) ON DELETE CASCADE,
    CONSTRAINT uk_document_pages_number UNIQUE (document_id, page_number)
);

CREATE INDEX idx_document_pages_document ON document_pages (document_id);
